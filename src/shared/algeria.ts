export function getWilayaByCode(code: string): WilayaInfo | undefined {
  const normalized = code.trim().padStart(2, '0');
  return ALGERIA_WILAYAS.find((w) => w.code === normalized);
}

export function getCommunesByWilayaCode(code: string): string[] {
  const normalized = String(code || '16').trim().padStart(2, '0');
  return ALGERIA_COMMUNES_BY_WILAYA[normalized] || ['Centre-ville'];
}
